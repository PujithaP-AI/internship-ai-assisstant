import subprocess
import sys


def install_if_missing(package, import_name=None):
    """
    Helper to install a package at runtime if it is missing.
    This is mainly for local/dev use so that the RAG code runs without
    asking people to manually pip install. In production, it is still
    better to manage dependencies via requirements.txt.
    """
    name = import_name or package
    try:
        __import__(name)
    except ImportError:
        print(f"[RAG] Missing '{package}', installing with pip...")
        try:
            subprocess.check_call([sys.executable, "-m", "pip", "install", package])
        except Exception as e:
            print(f"[RAG] Failed to install {package}: {e}")
            raise


